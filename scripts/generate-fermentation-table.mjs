// Generates src/domain/FermentationTable.ts from the committed CSV export of
// assets/bareme_fermentation_etendu_corrige.xlsx (TXCraig1's yeast-prediction table).
// Run: npm run fermentation-table
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, "..")
const csvPath = join(root, "assets", "bareme_fermentation_etendu_corrige.csv")
const outPath = join(root, "src", "domain", "FermentationTable.ts")

const lines = readFileSync(csvPath, "utf8").split(/\r?\n/).filter((l) => l.trim() !== "")

const parsePct = (s) => Number(s.replace("%", "").trim())
const cells = (line) => line.split(",")

// Rows 0,1,2 = ADY, IDY, CY header rows. Data columns start at index 3.
const adyRow = cells(lines[0])
const idyRow = cells(lines[1])
const cyRow = cells(lines[2])

const colCount = cyRow.length - 3
const cyPct = []
const adyPct = []
const idyPct = []
for (let c = 0; c < colCount; c++) {
  cyPct.push(parsePct(cyRow[3 + c]))
  adyPct.push(parsePct(adyRow[3 + c]))
  idyPct.push(parsePct(idyRow[3 + c]))
}

const temperaturesF = []
const hours = []
for (let r = 3; r < lines.length; r++) {
  const row = cells(lines[r])
  const tempF = Number(row[2])
  if (!Number.isFinite(tempF)) continue
  temperaturesF.push(tempF)
  const rowHours = []
  for (let c = 0; c < colCount; c++) {
    const raw = (row[3 + c] ?? "").trim()
    rowHours.push(raw === "" ? null : Number(raw))
  }
  hours.push(rowHours)
}

const fmtNumArr = (arr) => `[${arr.join(", ")}]`
const fmtHours = (grid) =>
  "[\n" +
  grid.map((row) => `    [${row.map((v) => (v === null ? "null" : v)).join(", ")}]`).join(",\n") +
  ",\n  ]"

const out = `// AUTO-GENERATED by scripts/generate-fermentation-table.mjs — do not edit by hand.
// Source: assets/bareme_fermentation_etendu_corrige.xlsx (TXCraig1 yeast-prediction table).
// hours[tempIndex][colIndex] = hours to full fermentation; null = off-chart (too long).

export type FermentationTable = {
  readonly temperaturesF: ReadonlyArray<number>
  readonly cyPct: ReadonlyArray<number>
  readonly adyPct: ReadonlyArray<number>
  readonly idyPct: ReadonlyArray<number>
  readonly hours: ReadonlyArray<ReadonlyArray<number | null>>
}

export const FERMENTATION_TABLE: FermentationTable = {
  temperaturesF: ${fmtNumArr(temperaturesF)},
  cyPct: ${fmtNumArr(cyPct)},
  adyPct: ${fmtNumArr(adyPct)},
  idyPct: ${fmtNumArr(idyPct)},
  hours: ${fmtHours(hours)},
}

export const FERMENTATION_MIN_F = ${Math.min(...temperaturesF)}
export const FERMENTATION_MAX_F = ${Math.max(...temperaturesF)}
`

writeFileSync(outPath, out)
console.log(
  `✓ ${outPath}\n  ${temperaturesF.length} temps (${Math.min(...temperaturesF)}–${Math.max(...temperaturesF)}°F) × ${colCount} yeast columns`,
)
