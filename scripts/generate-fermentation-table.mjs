// Generates src/domain/FermentationTable.ts by MERGING the two committed CSV
// exports of TXCraig1's yeast-prediction tables:
//   - bareme_fermentation_etendu_corrige: 35–80 °F, yeast 0.01–3% (wide yeast axis)
//   - bareme_fermentation_levure:         35–95 °F, yeast 0.01–1%  (wide temp axis)
// They agree on the overlapping region. Merge = union of temperatures (35–95 °F)
// × the wide yeast axis (0.01–3%); the warm zone (81–95 °F) only has data up to
// 1% (null beyond).
// Run: npm run fermentation-table
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, "..")
const outPath = join(root, "src", "domain", "FermentationTable.ts")

const parsePct = (s) => Number(s.replace("%", "").trim())

// Parse one CSV into { temperaturesF, cyPct, adyPct, idyPct, hours[t][c] }.
// Header rows (ADY/IDY/CY) are found by their first cell, so a leading title /
// blank lines don't matter. Data columns start at index 3.
const parseTable = (path) => {
  const lines = readFileSync(path, "utf8").split(/\r?\n/).filter((l) => l.trim() !== "")
  const rows = lines.map((l) => l.split(","))
  const find = (tag) => rows.find((r) => r[0].trim() === tag)
  const adyRow = find("ADY")
  const idyRow = find("IDY")
  const cyRow = find("CY")
  const cyIndex = rows.indexOf(cyRow)

  const colCount = cyRow.length - 3
  const cyPct = []
  const adyPct = []
  const idyPct = []
  for (let c = 0; c < colCount; c++) {
    cyPct.push(parsePct(cyRow[3 + c]))
    adyPct.push(parsePct(adyRow[3 + c]))
    idyPct.push(parsePct(idyRow[3 + c]))
  }

  const temperaturesF = []
  const hours = []
  for (let r = cyIndex + 1; r < rows.length; r++) {
    const tempF = Number(rows[r][2])
    if (!Number.isFinite(tempF)) continue
    temperaturesF.push(tempF)
    const rowHours = []
    for (let c = 0; c < colCount; c++) {
      const raw = (rows[r][3 + c] ?? "").trim()
      rowHours.push(raw === "" ? null : Number(raw))
    }
    hours.push(rowHours)
  }
  return { temperaturesF, cyPct, adyPct, idyPct, hours }
}

const master = parseTable(join(root, "assets", "bareme_fermentation_etendu_corrige.csv"))
const ext = parseTable(join(root, "assets", "bareme_fermentation_levure.csv"))

// The extended table's yeast columns must be a prefix of the master's.
for (let c = 0; c < ext.cyPct.length; c++) {
  if (ext.cyPct[c] !== master.cyPct[c]) {
    throw new Error(`Column mismatch at ${c}: ${ext.cyPct[c]} vs ${master.cyPct[c]}`)
  }
}

const cyPct = master.cyPct
const adyPct = master.adyPct
const idyPct = master.idyPct

const allTemps = [...new Set([...master.temperaturesF, ...ext.temperaturesF])].sort((a, b) => a - b)
const hours = allTemps.map((t) => {
  const mi = master.temperaturesF.indexOf(t)
  if (mi >= 0) return master.hours[mi] // full wide-yeast row
  const ei = ext.temperaturesF.indexOf(t)
  const extRow = ext.hours[ei]
  return cyPct.map((_, c) => (c < extRow.length ? extRow[c] : null)) // pad with null past 1%
})

const fmtNumArr = (arr) => `[${arr.join(", ")}]`
const fmtHours = (grid) =>
  "[\n" +
  grid.map((row) => `    [${row.map((v) => (v === null ? "null" : v)).join(", ")}]`).join(",\n") +
  ",\n  ]"

const out = `// AUTO-GENERATED by scripts/generate-fermentation-table.mjs — do not edit by hand.
// Merged from TXCraig1's two yeast-prediction tables (assets/*.xlsx).
// hours[tempIndex][colIndex] = hours to full fermentation; null = off-chart.

export type FermentationTable = {
  readonly temperaturesF: ReadonlyArray<number>
  readonly cyPct: ReadonlyArray<number>
  readonly adyPct: ReadonlyArray<number>
  readonly idyPct: ReadonlyArray<number>
  readonly hours: ReadonlyArray<ReadonlyArray<number | null>>
}

export const FERMENTATION_TABLE: FermentationTable = {
  temperaturesF: ${fmtNumArr(allTemps)},
  cyPct: ${fmtNumArr(cyPct)},
  adyPct: ${fmtNumArr(adyPct)},
  idyPct: ${fmtNumArr(idyPct)},
  hours: ${fmtHours(hours)},
}

export const FERMENTATION_MIN_F = ${Math.min(...allTemps)}
export const FERMENTATION_MAX_F = ${Math.max(...allTemps)}
`

writeFileSync(outPath, out)
console.log(
  `✓ ${outPath}\n  ${allTemps.length} temps (${Math.min(...allTemps)}–${Math.max(...allTemps)}°F) × ${cyPct.length} yeast columns (merged)`,
)
